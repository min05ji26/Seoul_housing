# ===========================================================================
# 자동 입력 주입 메커니즘
# ===========================================================================

def run_with_inputs(scenario_id):
    """선택된 시나리오의 입력값을 stdin에 주입하고 v5 main 실행"""
    
    if scenario_id not in SCENARIOS:
        print(f"[오류] 시나리오 {scenario_id} 없음. 사용 가능: {list(SCENARIOS.keys())}")
        return
    
    scenario = SCENARIOS[scenario_id]
    print("=" * 70)
    print(f"시나리오 {scenario_id}: {scenario['name']}")
    print(f"설명: {scenario['description']}")
    print(f"입력값 개수: {len(scenario['inputs'])}")
    print("=" * 70)
    print()
    
    # stdin에 입력값 주입
    inputs_text = "\n".join(scenario["inputs"]) + "\n"
    sys.stdin = io.StringIO(inputs_text)
    
    # 테스트 모드 활성화 (시나리오 3 이상: 청년정책 포함)
    # API 호출 없이 MOCK_POLICIES로 동작하게 하여 불필요한 호출 차단
    import youth_policy_module
    youth_policy_module._TEST_MODE = True
    youth_policy_module._POLICY_CACHE = []  # 이전 캐시 초기화

    # v5 import 후 main 실행
    try:
        import importlib.util
        spec = importlib.util.spec_from_file_location(
            "v5_module",
            "housing_recommendation_v5.py"
        )
        v5 = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(v5)

        # v5에 main() 함수가 있다고 가정. 없으면 직접 호출 부분 확인 필요
        if hasattr(v5, "main"):
            v5.main()
        else:
            print("[안내] main() 함수 없음. 파일 끝 if __name__ 블록 확인 필요")

    except EOFError:
        print()
        print("=" * 70)
        print("[안내] 입력값이 부족함. 시나리오의 inputs 리스트에 항목 추가 필요")
        print("=" * 70)
    except Exception as e:
        print()
        print("=" * 70)
        print(f"[오류] {type(e).__name__}: {e}")
        print("=" * 70)
        import traceback
        traceback.print_exc()
    finally:
        youth_policy_module._TEST_MODE = False


# ===========================================================================
# 진입점
# ===========================================================================

if __name__ == "__main__":
    # 명령줄 인자 또는 기본값
    if len(sys.argv) > 1:
        scenario_id = int(sys.argv[1])
    else:
        scenario_id = 1   # 기본값: 시나리오 1
    
    run_with_inputs(scenario_id)
